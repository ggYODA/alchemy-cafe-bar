// Current language (default: Greek)
let currentLanguage = localStorage.getItem('alchemy_language') || 'el';

// Initialize language on page load
document.addEventListener('DOMContentLoaded', function() {
    initializeLanguageSystem();
});

/**
 * Initialize the language system
 */
function initializeLanguageSystem() {
    // Set initial language
    setLanguage(currentLanguage);
    
    // Attach event listeners to language buttons
    const langOptions = document.querySelectorAll('.lang-option');
    langOptions.forEach(option => {
        option.addEventListener('click', function() {
            const lang = this.getAttribute('data-lang');
            setLanguage(lang);
            closeLanguageMenu();
        });
    });
    
    // Language menu toggle
    const langBtn = document.getElementById('langBtn');
    if (langBtn) {
        langBtn.addEventListener('click', toggleLanguageMenu);
    }
    
    // Close menu when clicking outside
    document.addEventListener('click', function(event) {
        const langSelector = document.querySelector('.language-selector');
        if (langSelector && !langSelector.contains(event.target)) {
            closeLanguageMenu();
        }
    });
}

/**
 * Set the current language and update all text
 */
function setLanguage(lang) {
    if (!translations[lang]) {
        console.warn(`Language "${lang}" not found. Using English instead.`);
        lang = 'en';
    }
    
    currentLanguage = lang;
    localStorage.setItem('alchemy_language', lang);
    
    // Set HTML lang attribute
    document.documentElement.lang = lang;
    
    // Update all elements with data-i18n attribute
    const translatableElements = document.querySelectorAll('[data-i18n]');
    translatableElements.forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang][key]) {
            element.textContent = translations[lang][key];
        } else {
            console.warn(`Translation key "${key}" not found for language "${lang}"`);
        }
    });
    
    // Update language button to show current language
    updateLanguageButton(lang);
}

/**
 * Get translated text for a key
 */
function t(key) {
    return translations[currentLanguage]?.[key] || translations['en']?.[key] || key;
}

/**
 * Toggle language menu visibility
 */
function toggleLanguageMenu() {
    const langMenu = document.getElementById('langMenu');
    if (langMenu) {
        langMenu.classList.toggle('active');
    }
}

/**
 * Close language menu
 */
function closeLanguageMenu() {
    const langMenu = document.getElementById('langMenu');
    if (langMenu) {
        langMenu.classList.remove('active');
    }
}

/**
 * Update the language button to show the current language code
 */
function updateLanguageButton(lang) {
    const langBtn = document.getElementById('langBtn');
    if (langBtn) {
        const langNames = {
            el: '🇬🇷',
            en: '🇬🇧',
            uk: '🇺🇦',
            ru: '🇷🇺',
            de: '🇩🇪',
            fr: '🇫🇷',
            es: '🇪🇸',
            ro: '🇷🇴'
        };
        langBtn.textContent = langNames[lang] || '🌐';
    }
}
